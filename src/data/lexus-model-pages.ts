type PhotoLicense = 'CC BY-SA 4.0' | 'CC0 1.0';

function photo(
  asset: string,
  file: string,
  alt: string,
  authorName: string,
  authorSlug: string,
  licenseName: PhotoLicense,
  width: number,
  height: number,
  caption: string,
): NonNullable<ModelPageData['image']> {
  const licenseUrl = licenseName === 'CC0 1.0'
    ? 'https://creativecommons.org/publicdomain/zero/1.0/deed.es'
    : 'https://creativecommons.org/licenses/by-sa/4.0/deed.es';

  return {
    src: `/images/models/commons/model-lexus-${asset}.jpg`,
    alt,
    caption: `${caption} Imagen redimensionada para web.`,
    width,
    height,
    sourceTitle: file,
    sourceUrl: `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(file.replaceAll(' ', '_'))}`,
    authorName,
    authorUrl: `https://commons.wikimedia.org/wiki/User:${authorSlug}`,
    licenseName,
    licenseUrl,
  };
}

